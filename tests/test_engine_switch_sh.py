# --- setup.sh writes the engine record back ----------------------------------

@posix_only
@pytest.mark.parametrize("line", ["export FLUBNF_ENGINE=private",
                                  "export FLUBNF_ENGINE=public"])
def test_setup_sh_writes_the_engine_record_back_when_it_rewrites_the_file(
        tmp_path, line):
    """The real setup.sh, with a Python 3.12, pip and the analysis venv as
    stand-ins and no hub fetch: its rewrite of .flubnf.env carries the
    engine record and the public venv's path through, once, run after
    run."""
    repo, home = tmp_path / "flubnf", tmp_path / "home"
    repo.mkdir()
    home.mkdir()
    shutil.copy(REPO / "setup.sh", repo / "setup.sh")
    for name in ("pip", "python"):
        _script(repo / ".venv" / "bin" / name, "exit 0\n")
    stub = tmp_path / "stub-bin"
    _script(stub / "python3.12", "exit 0\n")      # passes the version test
    envf = repo / ".flubnf.env"
    envf.write_text('export FLUBNF_HUB="/x/hub"\n'
                    f"{line}\n"
                    'export FLUBNF_PY_ENGINE_PUBLIC="/p/bin/python"\n')
    env = {k: v for k, v in os.environ.items() if not k.startswith("FLUBNF_")}
    env.update({"HOME": str(home), "FLUBNF_NO_DATA": "1",
                "GIT_TERMINAL_PROMPT": "0",
                "PATH": f"{stub}{os.pathsep}{os.environ['PATH']}"})
    for _ in range(2):
        out = subprocess.run([BASH, str(repo / "setup.sh")], env=env,
                             stdin=subprocess.DEVNULL, capture_output=True,
                             text=True, timeout=120)
        assert "wrote " + str(envf) in out.stdout, out.stdout + out.stderr
        lines = envf.read_text().splitlines()
        assert lines.count(line) == 1, lines
        assert lines.count('export FLUBNF_PY_ENGINE_PUBLIC="/p/bin/python"') == 1, lines
        assert sum("FLUBNF_ENGINE=" in ln for ln in lines) == 1, lines
    private = line.endswith("private")
    assert ("this copy is set to the private engine (the fallback)"
            in out.stdout) is private


