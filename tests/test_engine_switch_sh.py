# --- install.sh on a copy that is already there -----------------------------

def _install(tmp_path: Path, *, route: str | None, record: str | None,
             engine_rc: int = 0) -> tuple:
    """install.sh on a folder that is already a clone (nothing is cloned),
    with setup.sh and setup_engine.sh stand-ins; the copy's .flubnf.env
    records `record` as its engine (None: no file)."""
    dest, home, rec = tmp_path / "flubnf", tmp_path / "home", tmp_path / "rec"
    (dest / ".git").mkdir(parents=True)
    home.mkdir()
    _script(dest / "setup.sh", f'echo setup.sh >> "{rec}"\n')
    _script(dest / "setup_engine.sh",
            f'echo "$* engine=${{FLUBNF_ENGINE:-}}" >> "{rec}"\nexit {engine_rc}\n')
    if record is not None:
        (dest / ".flubnf.env").write_text(
            'export FLUBNF_HUB="/x/hub"\n'
            f"export FLUBNF_ENGINE={record}\n")
    env = {k: v for k, v in os.environ.items() if not k.startswith("FLUBNF_")}
    env.update({"HOME": str(home), "GIT_TERMINAL_PROMPT": "0",
                "FLUBNF_DIR": str(dest)})
    if route is not None:
        env["FLUBNF_ENGINE"] = route
    out = subprocess.run([BASH, str(INSTALL)], env=env, stdin=subprocess.DEVNULL,
                         capture_output=True, text=True, timeout=60)
    calls = rec.read_text().splitlines() if rec.exists() else []
    return out, calls


@posix_only
@pytest.mark.parametrize("route, record, flag", [
    (None, "private", "--private"),          # the plain line keeps it
    (None, '" PRIVATE "', "--private"),
    ("", "private", "--private"),            # empty says nothing
    ("public", "private", "--public"),       # named: the default again
    (None, "public", "--public"),
    (None, "pubic", "--public"),             # names no engine: the default
    (None, None, "--public"),
])
def test_install_keeps_a_private_record_unless_told_otherwise(
        tmp_path, route, record, flag):
    out, calls = _install(tmp_path, route=route, record=record)
    assert out.returncode == 0, out.stdout + out.stderr
    assert calls[0] == "setup.sh" and calls[1].startswith(f"{flag} "), calls
    kept = ("This copy is set to the private engine (the fallback) in its "
            ".flubnf.env, and it stays so;")
    assert (kept in out.stdout) is (not route and flag == "--private")


