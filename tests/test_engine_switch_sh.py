def _launcher(tmp_path: Path, record: str | None, setup_rc: int = 0) -> tuple:
    """A clone for the real FluBNF.command (no .git: no update) whose
    .flubnf.env holds `record` (None: no file), with console and
    setup_engine.sh stand-ins that record each call; the stand-in installer
    exits `setup_rc`."""
    repo, rec = tmp_path / "clone", tmp_path / "rec"
    rec.mkdir()
    (repo / "scripts").mkdir(parents=True)
    shutil.copy(REPO / "FluBNF.command", repo / "FluBNF.command")
    shutil.copy(LOCKPY, repo / "scripts" / "engine_lock.py")
    (repo / "pyproject.toml").write_text("[project]\n")
    _script(repo / ".venv" / "bin" / "flubnf", f'echo "$*" >> "{rec}/console"\n')
    _script(repo / ".venv" / "bin" / "python", f'exec "{sys.executable}" "$@"\n')
    shutil.copy(repo / "pyproject.toml", repo / ".venv" / ".pyproject.stamp")
    _script(repo / "setup_engine.sh",
            f'echo "$* engine=$FLUBNF_ENGINE" >> "{rec}/setup"\n'
            f'[ "${{1:-}}" = --print-bundle ] && exit 0\nexit {setup_rc}\n')
    if record is not None:
        (repo / ".flubnf.env").write_text(record + "\n")
    return repo, rec


def _open(repo: Path, tmp_path: Path) -> subprocess.CompletedProcess:
    env = {k: v for k, v in os.environ.items()
           if not k.startswith("FLUBNF_") and k != "TERM_PROGRAM"}
    env.update({"HOME": str(tmp_path), "TMPDIR": str(tmp_path)})
    return subprocess.run([BASH, str(repo / "FluBNF.command")], env=env,
                          stdin=subprocess.DEVNULL, capture_output=True,
                          text=True, timeout=60)


@posix_only
@pytest.mark.parametrize("record", RECORDS)
def test_the_launcher_reads_a_private_record_in_any_case_or_quoting(tmp_path, record):
    """FluBNF.command takes the private branch, with the route passed to
    the installer as plain `private`."""
    repo, rec = _launcher(tmp_path, record)
    out = _open(repo, tmp_path)
    assert out.returncode == 0, out.stdout + out.stderr
    calls = (rec / "setup").read_text().splitlines()
    # (--print-bundle reads no route; the install gets it normalised)
    assert len(calls) == 2 and calls[0].startswith("--print-bundle "), calls
    assert calls[1] == " engine=private", calls
    assert "neither private nor public" not in out.stdout
    assert "public engine" not in out.stdout


@posix_only
def test_a_public_install_that_succeeds_clears_the_exit_3_stamp(tmp_path):
    """A stamp from an earlier exit 3 that no longer matches (the lock, the
    script or the system changed) earns a new try; when that install
    succeeds, the stamp goes, so a later exit 3 is said afresh."""
    repo, rec = _launcher(tmp_path, None)
    _lock(repo / "engine-requirements.txt")
    stamp = repo / ".venv" / ".public-engine-attempt"
    stamp.write_text("an older script:lock:Darwin arm64:15.0\n")
    out = _open(repo, tmp_path)
    assert out.returncode == 0, out.stdout + out.stderr
    assert (rec / "setup").read_text().splitlines() == [" engine=public"]
    assert "· public engine ready" in out.stdout
    assert not stamp.exists()
