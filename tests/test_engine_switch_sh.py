"""The macOS and Linux engine scripts, after the cutover review
(docs/ENGINE.md): the public engine is the default and the private engine,
the lab's fork, the fallback that runs only where it is chosen.

Pinned here, each by running the real script with stand-ins (nothing is
downloaded or installed):

- a conda that cannot make Python 3.12 (offline, an unreachable channel)
  is exit 1, which FluBNF.command tries again on its next open; exit 3,
  which it stamps as "this machine cannot run the public engine", is kept
  for no Python 3.12 and no conda at all;
- ./setup_engine.sh --private tries the venv and checkout the copy
  recorded before the defaults, and keeps them when they load;
- the --private switch never skips the replacement of an unpacked private
  copy by a different, newer engine archive (FLUBNF_PYBNF_BUNDLE or the
  search), and never downgrades one;
- install.sh pasted again on a copy that records the private engine keeps
  it, and says the engine file paragraph only when the private install
  did not finish;
- setup.sh's rewrite of .flubnf.env writes the engine record back, run
  for real;
- a private record in any case or quoting is read as private by
  setup_engine.sh, SetupEngine.command and FluBNF.command;
- a public install that succeeds clears FluBNF.command's exit-3 stamp.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import tarfile
import time
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
SETUP = REPO / "setup_engine.sh"
LOCKPY = REPO / "scripts" / "engine_lock.py"
INSTALL = REPO / "install.sh"
BASH = "/bin/bash" if sys.platform == "darwin" else "bash"

posix_only = pytest.mark.skipif(
    sys.platform.startswith("win"),
    reason="setup_engine.sh and install.sh are the POSIX route")

COMMIT = "8410f794e3fa4817572fd07fceb043ddec39d77b"
URL = ("https://github.com/elyfmiller/flubnf/releases/download/"
       f"pybnf-{COMMIT}/pybnf-1.8.1-py3-none-any.whl")
SWITCHED = ("the private engine is installed and works: this copy runs it "
            "now (the fallback). ./setup_engine.sh --public goes back to the "
            "default.")
FALLBACK = ("The private engine is installed here: ./setup_engine.sh "
            "--private switches this copy to it (the fallback).")


def _lock(path: Path) -> Path:
    """A lock of the shape pip-compile --generate-hashes writes."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "#\n# This file is autogenerated by pip-compile with Python 3.12\n#\n"
        f"bngsim[antimony]==0.15.1 \\\n    --hash=sha256:{'11' * 32}\n"
        "    # via -r engine-requirements.in\n"
        f"pybnf @ {URL} \\\n    --hash=sha256:{'ab' * 32}\n"
        "    # via -r engine-requirements.in\n", encoding="utf-8")
    return path


def _repo(tmp_path: Path, script: str | None = None) -> Path:
    """setup_engine.sh (or `script`, its text) in a folder of its own, so
    the .flubnf.env it writes is the test's."""
    repo = tmp_path / "flubnf"
    (repo / "scripts").mkdir(parents=True)
    dest = repo / "setup_engine.sh"
    if script is None:
        shutil.copy(SETUP, dest)
    else:
        dest.write_text(script, encoding="utf-8")
    shutil.copy(LOCKPY, repo / "scripts" / "engine_lock.py")
    return repo


def _run(repo: Path, home: Path, *args: str, **env) -> subprocess.CompletedProcess:
    base = {k: v for k, v in os.environ.items() if not k.startswith("FLUBNF_")}
    base.update({"HOME": str(home), "GIT_TERMINAL_PROMPT": "0"})
    base.update({k: str(v) for k, v in env.items()})
    return subprocess.run([BASH, str(repo / "setup_engine.sh"), *args],
                          capture_output=True, text=True, timeout=120,
                          stdin=subprocess.DEVNULL, env=base)


def _script(path: Path, body: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("#!/bin/sh\n" + body)
    path.chmod(0o755)
    return path


# --- the public route: a failed conda create is exit 1, never 3 ------------

def _no_machine_python312(tmp_path: Path) -> str:
    """setup_engine.sh with find_python312's fixed places (Homebrew,
    python.org, /opt/anaconda3) moved under the test's folder, where none
    exists. The rest of the script is the real one."""
    src = SETUP.read_text(encoding="utf-8")
    start = src.index("find_python312() {")
    end = src.index("\n}\n", start)
    body = src[start:end]
    root = tmp_path / "machine"
    moved, n = re.subn(r'(?<=[\s"])/(?=[A-Za-z])', f"{root}/", body)
    assert n >= 5, f"find_python312's fixed places moved: {n}\n{body}"
    assert "$HOME/.venvs/flubnf-public-py312" in moved
    return src[:start] + moved + src[end:]


def _path_without_python(tmp_path: Path, conda: str | None) -> str:
    """PATH: Apple silicon's uname, a conda stand-in (`conda` is its body,
    or None for no conda) and every tool of /usr/bin and /bin but Python
    and conda."""
    stub, tools = tmp_path / "stub-bin", tmp_path / "tools"
    _script(stub / "uname",
            'case "$1" in -s) echo Darwin ;; -m) echo arm64 ;; '
            '-sm) echo "Darwin arm64" ;; *) echo Darwin ;; esac\n')
    _script(stub / "sw_vers", "echo 15.1\n")
    if conda is not None:
        _script(stub / "conda", conda)
    tools.mkdir()
    for d in ("/usr/bin", "/bin"):
        if not os.path.isdir(d):
            continue
        for name in os.listdir(d):
            # GitHub's Linux image puts conda in /usr/bin: a test that
            # says "no conda" must not find the real one there
            # lexists, not exists: a name already linked to a broken
            # symlink (GitHub's ubuntu-26.04 has one, grub-ntldr-img) is
            # there all the same
            if (name.startswith(("python", "conda", "mamba", "micromamba"))
                    or os.path.lexists(tools / name)):
                continue
            os.symlink(os.path.join(d, name), tools / name)
    return f"{stub}{os.pathsep}{tools}"


@posix_only
@pytest.mark.parametrize("conda, rc", [
    # offline, or conda's channel unreachable: run it again later
    ('echo "$*" >> "$CONDA_CALLS"\n'
     'echo "CondaHTTPError: HTTP 000 CONNECTION FAILED" >&2\nexit 1\n', 1),
    # no Python 3.12 and nothing to make one: retrying cannot fix that
    (None, 3),
], ids=["conda-offline", "no-conda"])
@pytest.mark.parametrize("private", [True, False])
def test_a_conda_that_cannot_make_python_312_is_exit_1_never_3(
        tmp_path, conda, rc, private):
    repo = _repo(tmp_path, _no_machine_python312(tmp_path))
    home = tmp_path / "home"
    home.mkdir()
    _lock(repo / "engine-requirements.txt")
    # the lock is read by the clone's own Python, as on a set-up copy
    _script(repo / ".venv" / "bin" / "python", f'exec "{sys.executable}" "$@"\n')
    calls = tmp_path / "conda-calls"
    env = {"PATH": _path_without_python(tmp_path, conda),
           "CONDA_CALLS": calls}
    if private:
        env.update(_private_engine(tmp_path / "priv"))
    out = _run(repo, home, **env)
    said = out.stdout + out.stderr
    assert out.returncode == rc, said
    if rc == 1:
        assert calls.read_text().split()[:2] == ["create", "-y"], said
        assert "CONNECTION FAILED" in out.stderr
        assert ("conda could not make a Python 3.12 (its error is above)"
                in out.stdout), said
        assert "run this again with the network up" in out.stdout
        assert "none was found or creatable" not in said
        # exit 1 names no fallback: FluBNF.command says that, and retries
        assert FALLBACK not in out.stdout
    else:
        assert not calls.exists()
        assert ("the public engine needs Python 3.12, and none was found or "
                "creatable.") in out.stdout
        assert (FALLBACK in out.stdout) is private
    assert not (home / ".venvs" / "flubnf-public").exists()
    assert "FLUBNF_PY_ENGINE_PUBLIC" not in (
        (repo / ".flubnf.env").read_text() if (repo / ".flubnf.env").exists()
        else "")


# --- --private: the recorded venv and checkout first, then the defaults ------

def _private_engine(where: Path, *, loads: bool = True,
                    calls: Path | None = None) -> dict:
    """A private engine stand-in at `where`: a venv whose python records
    each call ($0 and its arguments) and passes setup_engine.sh's verify
    (or fails it), and a fork with pybnf/pf.py. Returns the record's names
    for them."""
    venv, fork = where / "venv", where / "PyBNF-fork"
    calls = calls or where.parent / "private-calls"
    (fork / "pybnf").mkdir(parents=True)
    (fork / "pybnf" / "pf.py").write_text("# the filter\n")
    _script(venv / "bin" / "python",
            f'echo "$0 $*" >> "{calls}"\n'
            + ('echo "  + pybnf with fit_type=pf -- engine ready"\nexit 0\n'
               if loads else "exit 1\n"))
    return {"FLUBNF_PY_ENGINE": venv / "bin" / "python", "FLUBNF_PYBNF": fork}


def _record(repo: Path, **names) -> Path:
    envf = repo / ".flubnf.env"
    envf.write_text('export FLUBNF_HUB="/x/hub"\n'
                    + "".join(f'export {k}="{v}"\n' for k, v in names.items()))
    return envf


def _default_fork(home: Path, name: str = "PyBNF-pf") -> Path:
    fork = home / "GitHub" / name
    (fork / "pybnf").mkdir(parents=True)
    (fork / "pybnf" / "pf.py").write_text("# the filter\n")
    return fork


@posix_only
def test_private_keeps_the_venv_and_checkout_the_copy_recorded(tmp_path):
    """The record names a venv other than ~/.venvs/flubnf-engine and the
    fork PyBNF-Private, while the default search would take PyBNF-pf: the
    switch verifies the recorded pair, keeps it, and installs nothing."""
    repo, home = _repo(tmp_path), tmp_path / "home"
    calls = tmp_path / "private-calls"
    rec = _private_engine(tmp_path / "lab", calls=calls)
    envf = _record(repo, FLUBNF_PY_ENGINE_PUBLIC="/p/bin/python", **rec)
    _default_fork(home)                       # what the search would take
    out = _run(repo, home, "--private")
    assert out.returncode == 0, out.stdout + out.stderr
    assert SWITCHED in out.stdout
    text = envf.read_text()
    assert f'export FLUBNF_PY_ENGINE="{rec["FLUBNF_PY_ENGINE"]}"' in text, text
    assert f'export FLUBNF_PYBNF="{rec["FLUBNF_PYBNF"]}"' in text, text
    assert text.count("FLUBNF_PY_ENGINE=") == 1 and text.count("FLUBNF_PYBNF=") == 1
    assert "export FLUBNF_ENGINE=private" in text
    assert 'export FLUBNF_PY_ENGINE_PUBLIC="/p/bin/python"' in text
    assert calls.read_text().splitlines() == [
        f"{rec['FLUBNF_PY_ENGINE']} - {rec['FLUBNF_PYBNF']}"]
    assert not (home / ".venvs").exists(), "a second private venv was made"

    # a checkout named in this shell is a choice: it is used and recorded
    other = _default_fork(home, "PyBNF-Private")
    out = _run(repo, home, "--private", FLUBNF_PYBNF=other)
    assert out.returncode == 0, out.stdout + out.stderr
    text = envf.read_text()
    assert f'export FLUBNF_PYBNF="{other}"' in text, text
    assert f'export FLUBNF_PY_ENGINE="{rec["FLUBNF_PY_ENGINE"]}"' in text, text


@posix_only
@pytest.mark.parametrize("broken", ["venv", "checkout"])
def test_private_goes_on_to_the_defaults_when_the_record_does_not_load(
        tmp_path, broken):
    """A recorded venv that is gone, or a recorded checkout with no
    engine in it (setup.sh records ~/GitHub/PyBNF-pf whether or not it
    exists): the defaults are tried next, and recorded when they load."""
    repo, home = _repo(tmp_path), tmp_path / "home"
    calls = tmp_path / "private-calls"
    rec = _private_engine(tmp_path / "lab", calls=calls)
    if broken == "venv":
        shutil.rmtree(tmp_path / "lab" / "venv")
    else:
        rec["FLUBNF_PYBNF"] = home / "GitHub" / "nothing-here"
    envf = _record(repo, **rec)
    fork = _default_fork(home, "PyBNF-Private")
    default_py = _script(home / ".venvs" / "flubnf-engine" / "bin" / "python",
                         f'echo "$0 $*" >> "{calls}"\n'
                         'echo "  + engine ready"\nexit 0\n')
    out = _run(repo, home, "--private")
    assert out.returncode == 0, out.stdout + out.stderr
    assert SWITCHED in out.stdout
    text = envf.read_text()
    if broken == "venv":
        assert f'export FLUBNF_PY_ENGINE="{default_py}"' in text, text
    else:
        # the recorded venv still loads, with the checkout the search found
        assert f'export FLUBNF_PY_ENGINE="{rec["FLUBNF_PY_ENGINE"]}"' in text, text
    assert f'export FLUBNF_PYBNF="{fork}"' in text, text


# --- --private never skips a replacement archive ---------------------------

_SAFE = {"filter": "data"} if hasattr(tarfile, "data_filter") else {}


def _fake_archive(tmp_path: Path, stamp: str, name: str) -> Path:
    """An engine archive of cut_engine_archive.sh's shape: one top folder
    holding pybnf/pf.py, setup.py and a VERSION stamp."""
    root = tmp_path / f"src-{stamp.split()[-1]}" / "PyBNF-Private"
    (root / "pybnf").mkdir(parents=True)
    (root / "pybnf" / "pf.py").write_text("class ParticleFilter: pass\n")
    (root / "pybnf" / "__init__.py").write_text("")
    (root / "setup.py").write_text("from setuptools import setup; setup()\n")
    (root / "VERSION").write_text(stamp + "\n")
    arc = tmp_path / name
    with tarfile.open(arc, "w:gz") as t:
        t.add(root, arcname="PyBNF-Private")
    return arc


def _unpacked_install(tmp_path: Path, home: Path, stamp: str) -> dict:
    """An archive install of the private engine, working: an unpacked copy
    (no .git) with its VERSION stamped nine days ago, and a venv that
    loads. Returns the record's names for them."""
    arc = _fake_archive(tmp_path / "was", stamp, "was.tar.gz")
    with tarfile.open(arc) as t:
        t.extractall(tmp_path / "unpacked", **_SAFE)
    fork = home / "GitHub" / "PyBNF-Private"
    fork.parent.mkdir(parents=True, exist_ok=True)
    (tmp_path / "unpacked" / "PyBNF-Private").rename(fork)
    was = time.time() - 9 * 24 * 3600
    for f in (fork / "VERSION", fork):
        os.utime(f, (was, was))
    py = _script(tmp_path / "venv" / "bin" / "python",
                 'echo "  + pybnf with fit_type=pf -- engine ready"\nexit 0\n')
    return {"FLUBNF_PY_ENGINE": py, "FLUBNF_PYBNF": fork}


@posix_only
@pytest.mark.parametrize("offered", ["downloads", "named"])
def test_private_replaces_an_unpacked_copy_with_a_newer_archive(tmp_path, offered):
    """The build warning says: save the archive in Downloads and run
    ./setup_engine.sh --private. The engine on disk loads, so the switch
    alone would stop there; a different, newer archive goes in instead,
    the old copy moved aside. (FLUBNF_ENGINE_CHECKOUT_ONLY stops after the
    checkout: no pip.)"""
    repo, home = _repo(tmp_path), tmp_path / "home"
    for d in ("Downloads", "Desktop", "Documents"):
        (home / d).mkdir(parents=True)
    rec = _unpacked_install(tmp_path, home, "feature/particle-filter 3320d1f0")
    _record(repo, **rec)
    new = _fake_archive(tmp_path, "feature/particle-filter 2fdadee0",
                        "pybnf-pf-2fdadee0.tar.gz")
    env = {"FLUBNF_ENGINE_CHECKOUT_ONLY": "1"}
    if offered == "downloads":
        shutil.copy(new, home / "Downloads" / new.name)
    else:
        kept = tmp_path / "usb" / new.name
        kept.parent.mkdir()
        shutil.copy(new, kept)
        env["FLUBNF_PYBNF_BUNDLE"] = kept
    out = _run(repo, home, "--private", **env)
    said = out.stdout + out.stderr
    assert out.returncode == 0, said
    assert SWITCHED not in out.stdout
    assert "a different engine archive has arrived" in out.stdout, said
    fork = rec["FLUBNF_PYBNF"]
    assert (fork / "VERSION").read_text().strip() == \
        "feature/particle-filter 2fdadee0", said
    assert list(fork.parent.glob("PyBNF-Private.replaced-*")), said
    assert "export FLUBNF_ENGINE=private" in (repo / ".flubnf.env").read_text()


@posix_only
@pytest.mark.parametrize("archive", ["same-stamp", "older"])
def test_private_switches_when_no_archive_would_replace_the_copy(tmp_path, archive):
    """The same build again, or an older download left in Downloads: the
    switch stops at once, and the copy on disk is not touched."""
    repo, home = _repo(tmp_path), tmp_path / "home"
    (home / "Downloads").mkdir(parents=True)
    rec = _unpacked_install(tmp_path, home, "feature/particle-filter 2fdadee0")
    _record(repo, **rec)
    stamp = ("feature/particle-filter 2fdadee0" if archive == "same-stamp"
             else "feature/particle-filter 3320d1f0")
    landed = home / "Downloads" / "pybnf-pf-x.tar.gz"
    shutil.copy(_fake_archive(tmp_path, stamp, "x.tar.gz"), landed)
    if archive == "older":
        was = time.time() - 30 * 24 * 3600   # saved before the install
        os.utime(landed, (was, was))
    out = _run(repo, home, "--private", FLUBNF_ENGINE_CHECKOUT_ONLY="1")
    assert out.returncode == 0, out.stdout + out.stderr
    assert SWITCHED in out.stdout
    fork = rec["FLUBNF_PYBNF"]
    assert (fork / "VERSION").read_text().strip() == "feature/particle-filter 2fdadee0"
    assert not list(fork.parent.glob("*.replaced-*"))


