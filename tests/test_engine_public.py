"""The public engine's route on macOS and Linux (opt-in until the cutover;
docs/ENGINE.md): public PyBNF's Liu-West filter and bngsim from one lock,
engine-requirements.txt, into a venv of their own.

The lock is the engine lane's and not in the repository yet, so these tests
write sample locks of its shape (pip-compile's: a backslash continues a
line, "# via" lines under each pin) with made-up hashes, and stand-in venvs:
nothing here downloads or installs. Pinned: the wheel's URL and sha256 are
read from the lock (scripts/engine_lock.py) and nowhere else; a missing or
unusable lock stops the route before any venv is made; the public venv is
never one of the private engine's; the route is recorded only when asked for,
and the private record never takes the public one with it; the launcher
reinstalls only when the lock changed; a public reinstall needs no engine
file and leaves the private engine where it is; the private route's bngsim
comes from PyPI or not at all. Executing tests are POSIX-only; FluBNF.bat
and setup.ps1, the Windows twins, are pinned in test_windows_*.py.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
LOCKPY = REPO / "scripts" / "engine_lock.py"
SETUP = REPO / "setup_engine.sh"
COMMAND = REPO / "FluBNF.command"
BASH = "/bin/bash" if sys.platform == "darwin" else "bash"

posix_only = pytest.mark.skipif(
    sys.platform.startswith("win"),
    reason="setup_engine.sh and FluBNF.command are the POSIX route")

COMMIT = "8410f794e3fa4817572fd07fceb043ddec39d77b"
URL = ("https://github.com/elyfmiller/flubnf/releases/download/"
       f"pybnf-{COMMIT}/pybnf-1.8.1-py3-none-any.whl")
SHA = "ab" * 32


def _lock(path: Path, *, url: str = URL, sha: str = SHA,
          wheel: str | None = None, bngsim: str = "0.15.1") -> Path:
    """A lock as pip-compile --generate-hashes writes one."""
    if wheel is None:
        wheel = (f"pybnf @ {url} \\\n"
                 f"    --hash=sha256:{sha}\n"
                 "    # via -r engine-requirements.in\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "#\n# This file is autogenerated by pip-compile with Python 3.12\n#\n"
        f"bngsim[antimony]=={bngsim} \\\n"
        f"    --hash=sha256:{'11' * 32} \\\n"
        f"    --hash=sha256:{'22' * 32}\n"
        "    # via -r engine-requirements.in\n"
        f"numpy==2.5.4 \\\n    --hash=sha256:{'33' * 32}\n"
        "    # via\n    #   bngsim\n    #   pybnf\n"
        + wheel, encoding="utf-8")
    return path


def _lockpy(*args: str, **env) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(LOCKPY), *args],
                          capture_output=True, text=True, timeout=60,
                          env={**os.environ, **env})


def test_the_wheel_line_is_read_from_the_lock(tmp_path):
    lock = _lock(tmp_path / "engine-requirements.txt")
    out = _lockpy("wheel", str(lock))
    assert out.returncode == 0, out.stderr
    assert out.stdout.splitlines() == [URL, SHA]
    # the default is the repository's lock, FLUBNF_ENGINE_LOCK before it
    out = _lockpy("wheel", FLUBNF_ENGINE_LOCK=str(lock))
    assert out.stdout.splitlines() == [URL, SHA], out.stderr
    # CI fetches everything but the wheel, hashes kept, one line a package
    deps = _lockpy("deps", str(lock)).stdout.splitlines()
    assert [d.split()[0] for d in deps] == ["bngsim[antimony]==0.15.1", "numpy==2.5.4"]
    assert deps[0].count("--hash=sha256:") == 2 and "#" not in "".join(deps)


@pytest.mark.parametrize("case, says", [
    ("missing", "lock file is not here"),
    ("no-wheel", "no line for the PyBNF wheel"),
    ("twice", "names PyBNF 2 times"),
    ("http", "wheel at an https address"),
    ("sdist", "wheel at an https address"),
    ("no-hash", "exactly one --hash=sha256"),
    ("two-hashes", "exactly one --hash=sha256"),
])
def test_an_unusable_lock_is_refused_with_its_reason(tmp_path, case, says):
    lock = tmp_path / "engine-requirements.txt"
    one = f"pybnf @ {URL} --hash=sha256:{SHA}\n"
    wheel = {
        "no-wheel": "",
        "twice": one + one,
        "http": f"pybnf @ {URL.replace('https', 'http')} --hash=sha256:{SHA}\n",
        "sdist": f"pybnf @ {URL[:-len('-py3-none-any.whl')]}.tar.gz --hash=sha256:{SHA}\n",
        "no-hash": f"pybnf @ {URL}\n",
        "two-hashes": f"pybnf @ {URL} --hash=sha256:{SHA} --hash=sha256:{'cd' * 32}\n",
    }.get(case)
    if case != "missing":
        _lock(lock, wheel=wheel)
    out = _lockpy("wheel", str(lock))
    assert out.returncode == 2, out.stdout
    assert says in out.stderr, out.stderr
    assert out.stdout == ""


def _site(tmp_path: Path, *, url: str = URL, sha: str | None = SHA,
          bngsim: str = "0.15.1", direct: bool = True, lwf: bool = True) -> Path:
    """A stand-in for the public venv's site-packages: pybnf with (or
    without) the Liu-West filter and pip's PEP 610 record, and bngsim."""
    site = tmp_path / "site"
    filters = site / "pybnf" / "algorithms" / "filters"
    filters.mkdir(parents=True)
    for d in (site / "pybnf", site / "pybnf" / "algorithms", filters):
        (d / "__init__.py").write_text("")
    if lwf:
        (filters / "liu_west.py").write_text("class LiuWestFilter: pass\n")
    (site / "bngsim.py").write_text(f"__version__ = '{bngsim}'\n")
    for name, ver in (("pybnf", "1.8.1"), ("bngsim", bngsim)):
        info = site / f"{name}-{ver}.dist-info"
        info.mkdir()
        (info / "METADATA").write_text(
            f"Metadata-Version: 2.1\nName: {name}\nVersion: {ver}\n")
    if direct:
        arch = {"hashes": {"sha256": sha}} if sha else {}
        (site / "pybnf-1.8.1.dist-info" / "direct_url.json").write_text(
            json.dumps({"url": url, "archive_info": arch}))
    return site


@pytest.mark.parametrize("case, rc, says", [
    ("ready", 0, "public engine ready: pybnf 1.8.1 from pybnf-1.8.1-py3-none-any.whl, bngsim 0.15.1"),
    ("no-hash-recorded", 0, "public engine ready"),
    ("other-wheel", 1, "the lock names " + URL),
    ("other-sha", 1, "the lock names " + SHA),
    ("other-bngsim", 1, "bngsim here is 0.16.0; the lock pins 0.15.1"),
    ("not-from-a-wheel", 1, "not installed from a wheel address"),
    ("no-filter", 1, "does not load in this venv"),
])
def test_check_holds_the_venv_to_the_lock(tmp_path, case, rc, says):
    lock = _lock(tmp_path / "engine-requirements.txt")
    site = _site(tmp_path, **{
        "no-hash-recorded": {"sha": None},
        "other-wheel": {"url": URL.replace("8410f794", "deadbeef")},
        "other-sha": {"sha": "ef" * 32},
        "other-bngsim": {"bngsim": "0.16.0"},
        "not-from-a-wheel": {"direct": False},
        "no-filter": {"lwf": False},
    }.get(case, {}))
    out = _lockpy("check", str(lock), PYTHONPATH=str(site))
    assert out.returncode == rc, out.stdout + out.stderr
    assert says in out.stdout + out.stderr


# --- setup_engine.sh --public -------------------------------------------------

def _engine_repo(tmp_path: Path) -> Path:
    """setup_engine.sh and the lock reader in a folder of their own, so the
    .flubnf.env it writes is the test's."""
    repo = tmp_path / "flubnf"
    (repo / "scripts").mkdir(parents=True)
    shutil.copy(SETUP, repo / "setup_engine.sh")
    shutil.copy(LOCKPY, repo / "scripts" / "engine_lock.py")
    return repo


def _setup(repo: Path, home: Path, *args: str, **env) -> subprocess.CompletedProcess:
    base = {k: v for k, v in os.environ.items() if not k.startswith("FLUBNF_")}
    base.update({"HOME": str(home), "GIT_TERMINAL_PROMPT": "0"})
    base.update({k: str(v) for k, v in env.items()})
    return subprocess.run([BASH, str(repo / "setup_engine.sh"), *args],
                          capture_output=True, text=True, timeout=120, env=base)


def _ready_venv(venv: Path, site: Path) -> Path:
    """A public venv stand-in whose python is 3.12 to the version test and
    runs this interpreter on the stand-in site otherwise."""
    (venv / "bin").mkdir(parents=True)
    (venv / "pyvenv.cfg").write_text("version = 3.12.7\n")
    py = venv / "bin" / "python"
    py.write_text(
        "#!/bin/sh\n"
        'case "$*" in *"version_info[:2] == (3, 12)"*) exit 0 ;; esac\n'
        f'PYTHONPATH="{site}" exec "{sys.executable}" "$@"\n')
    py.chmod(0o755)
    return py


@posix_only
def test_a_missing_lock_stops_the_public_route_before_any_venv(tmp_path):
    repo, home = _engine_repo(tmp_path), tmp_path / "home"
    home.mkdir()
    out = _setup(repo, home, "--public")
    assert out.returncode == 1, out.stdout + out.stderr
    assert "lock file is not here" in out.stderr
    assert "cannot install yet" in out.stdout
    assert not (home / ".venvs").exists()
    assert not (repo / ".flubnf.env").exists()


@posix_only
@pytest.mark.parametrize("venv", [".venvs/flubnf", ".venvs/flubnf-engine/",
                                  "own-private"])
def test_the_public_venv_is_never_one_of_the_private_engines(tmp_path, venv):
    repo, home = _engine_repo(tmp_path), tmp_path / "home"
    home.mkdir()
    _lock(repo / "engine-requirements.txt")
    private = home / "own-private"
    out = _setup(repo, home, "--public", FLUBNF_PUBLIC_VENV=home / venv,
                 FLUBNF_ENGINE_VENV=private)
    assert out.returncode == 1, out.stdout + out.stderr
    assert "which is the private engine's" in out.stdout
    assert not (home / venv).exists()


@posix_only
@pytest.mark.parametrize("args, env, says", [
    (("--pubic",), {}, "unknown option: --pubic"),
    ((), {"FLUBNF_ENGINE": "lwf"}, 'FLUBNF_ENGINE is "lwf"'),
])
def test_an_unknown_route_or_option_is_refused(tmp_path, args, env, says):
    repo, home = _engine_repo(tmp_path), tmp_path / "home"
    home.mkdir()
    out = _setup(repo, home, *args, **env)
    assert out.returncode == 2 and says in out.stdout, out.stdout + out.stderr


@posix_only
def test_the_route_is_recorded_only_when_asked_and_keeps_the_private_record(tmp_path):
    repo, home = _engine_repo(tmp_path), tmp_path / "home"
    lock = _lock(repo / "engine-requirements.txt")
    venv = home / ".venvs" / "flubnf-public"
    py = _ready_venv(venv, _site(tmp_path))
    envf = repo / ".flubnf.env"
    envf.write_text('export FLUBNF_HUB="/x/hub"\n'
                    'export FLUBNF_PY_ENGINE="/x/engine/bin/python"\n'
                    'export FLUBNF_PY_ENGINE_PUBLIC="/old/bin/python"\n')

    # FLUBNF_ENGINE from the shell: the venv is recorded, the route is not
    out = _setup(repo, home, FLUBNF_ENGINE="public")
    assert out.returncode == 0, out.stdout + out.stderr
    assert "public engine ready" in out.stdout
    lines = envf.read_text().splitlines()
    assert lines == ['export FLUBNF_HUB="/x/hub"',
                     'export FLUBNF_PY_ENGINE="/x/engine/bin/python"',
                     f'export FLUBNF_PY_ENGINE_PUBLIC="{py}"'], lines
    # the stamp the launcher compares, the lock's own hash
    stamp = (venv / "flubnf-lock.sha256").read_text().strip()
    assert stamp == hashlib.sha256(lock.read_bytes()).hexdigest()

    # --public: the route too, once however often it runs
    for _ in range(2):
        out = _setup(repo, home, "--public")
        assert out.returncode == 0, out.stdout + out.stderr
    text = envf.read_text()
    assert text.count("export FLUBNF_ENGINE=public") == 1, text
    assert text.count("FLUBNF_PY_ENGINE_PUBLIC=") == 1, text
    assert 'export FLUBNF_PY_ENGINE="/x/engine/bin/python"' in text


@posix_only
def test_a_venv_that_holds_another_wheel_is_reinstalled_with_force(tmp_path):
    """pip keeps a package of the same version unless told otherwise, so a
    venv made from an older lock is reinstalled with --force-reinstall."""
    repo, home = _engine_repo(tmp_path), tmp_path / "home"
    _lock(repo / "engine-requirements.txt")
    venv = home / ".venvs" / "flubnf-public"
    py = _ready_venv(venv, _site(tmp_path, url=URL.replace("8410f794", "deadbeef")))
    calls = tmp_path / "pip-calls"
    # pip itself is a stand-in that records what it was asked
    py.write_text(py.read_text().replace(
        'PYTHONPATH=',
        f'case "$*" in *"-m pip install"*) echo "$*" >> "{calls}"; exit 1 ;; esac\n'
        'PYTHONPATH=', 1))
    out = _setup(repo, home, "--public")
    assert out.returncode == 1, out.stdout + out.stderr
    asked = calls.read_text()
    for flag in ("--require-hashes", "--only-binary :all:", "--force-reinstall",
                 "-r " + str(repo / "engine-requirements.txt")):
        assert flag in asked, asked
    assert "pip could not install the lock" in out.stdout
    assert not (repo / ".flubnf.env").exists()


def test_the_private_route_takes_bngsim_from_pypi_or_not_at_all():
    src = SETUP.read_text(encoding="utf-8")
    assert '"bngsim==0.15.1"' in src
    assert "git+" not in src and "FLUBNF_BNGSIM_REMOTE" not in src
    # and the private pins stay on the private route
    private = src.split("# ===== the private engine (the default)", 1)[1]
    assert '"numpy<2"' in private and '"dask==2022.12.1"' in private
    assert "numpy<2" not in src.split("# ===== the private engine (the default)", 1)[0]


# --- FluBNF.command -------------------------------------------------------------

def _command_repo(tmp_path: Path) -> tuple[Path, Path]:
    """A clone for the real FluBNF.command (no .git: no update), set to the
    public engine, its console and setup_engine.sh stand-ins that record
    each call."""
    repo, rec = tmp_path / "clone", tmp_path / "rec"
    rec.mkdir()
    (repo / "scripts").mkdir(parents=True)
    shutil.copy(COMMAND, repo / "FluBNF.command")
    shutil.copy(LOCKPY, repo / "scripts" / "engine_lock.py")
    (repo / "pyproject.toml").write_text("[project]\n")
    bin_ = repo / ".venv" / "bin"
    bin_.mkdir(parents=True)
    shutil.copy(repo / "pyproject.toml", repo / ".venv" / ".pyproject.stamp")
    for name, body in (
            ("flubnf", f'echo "$*" >> "{rec}/console"\nexit 0\n'),
            ("python", f'exec "{sys.executable}" "$@"\n')):
        (bin_ / name).write_text("#!/bin/bash\n" + body)
        (bin_ / name).chmod(0o755)
    setup = repo / "setup_engine.sh"
    setup.write_text(f'#!/bin/bash\necho "$* engine=$FLUBNF_ENGINE" >> "{rec}/setup"\nexit 0\n')
    setup.chmod(0o755)
    venv = tmp_path / "public"
    (venv / "bin").mkdir(parents=True)
    (venv / "bin" / "python").write_text("#!/bin/sh\nexit 0\n")
    (venv / "bin" / "python").chmod(0o755)
    (repo / ".flubnf.env").write_text(
        "export FLUBNF_ENGINE=public\n"
        f'export FLUBNF_PY_ENGINE_PUBLIC="{venv}/bin/python"\n')
    return repo, rec


def _command(repo: Path, tmp_path: Path) -> subprocess.CompletedProcess:
    env = {k: v for k, v in os.environ.items()
           if not k.startswith("FLUBNF_") and k != "TERM_PROGRAM"}
    env.update({"HOME": str(tmp_path), "TMPDIR": str(tmp_path)})
    return subprocess.run([BASH, str(repo / "FluBNF.command")], env=env,
                          stdin=subprocess.DEVNULL, capture_output=True,
                          text=True, timeout=60)


@posix_only
def test_the_launcher_reinstalls_the_public_engine_only_when_the_lock_changed(tmp_path):
    repo, rec = _command_repo(tmp_path)
    lock = _lock(repo / "engine-requirements.txt")
    stamp = tmp_path / "public" / "flubnf-lock.sha256"
    stamp.write_text(hashlib.sha256(lock.read_bytes()).hexdigest() + "\n")

    out = _command(repo, tmp_path)
    assert out.returncode == 0, out.stdout + out.stderr
    assert not (rec / "setup").exists(), out.stdout
    assert (rec / "console").read_text().splitlines()[-1] == "app"
    # the private engine's install is not this route's business
    assert "PF engine" not in out.stdout

    _lock(lock, bngsim="0.15.2")
    out = _command(repo, tmp_path)
    assert out.returncode == 0, out.stdout + out.stderr
    # no option: the route travels in FLUBNF_ENGINE, already recorded
    assert (rec / "setup").read_text().splitlines() == [" engine=public"]
    assert "its lock changed" in out.stdout

    lock.unlink()
    out = _command(repo, tmp_path)
    assert out.returncode == 0, out.stdout + out.stderr
    assert len((rec / "setup").read_text().splitlines()) == 1
    assert "cannot install yet" in out.stdout
    assert "lock file is not here" in out.stderr


# --- reinstall.sh ---------------------------------------------------------------

@posix_only
@pytest.mark.skipif(hasattr(os, "geteuid") and os.geteuid() == 0,
                    reason="reinstall.sh refuses to run as root")
def test_a_public_reinstall_needs_no_engine_file_and_leaves_the_private_engine(tmp_path):
    git = {"GIT_AUTHOR_NAME": "T", "GIT_AUTHOR_EMAIL": "t@example.invalid",
           "GIT_COMMITTER_NAME": "T", "GIT_COMMITTER_EMAIL": "t@example.invalid"}
    src = tmp_path / "src"
    src.mkdir()
    run = lambda *a, cwd=src: subprocess.run(  # noqa: E731
        ["git", *a], cwd=cwd, env={**os.environ, **git}, check=True,
        capture_output=True)
    run("init", "-q", "-b", "main", ".")
    (src / "README").write_text("stand-in\n")
    run("add", "README")
    run("commit", "-qm", "init")
    origin = tmp_path / "origin.git"
    run("clone", "-q", "--bare", str(src), str(origin), cwd=tmp_path)
    home = tmp_path / "home"
    for d in ("Downloads", "GitHub/flubnf/app/state", ".venvs/flubnf-engine",
              "GitHub/PyBNF-Private"):
        (home / d).mkdir(parents=True)
    archive = home / "Downloads" / "pybnf-pf-2fdadee0.tar.gz"
    archive.write_bytes(b"the private engine's file")
    env = {k: v for k, v in os.environ.items() if not k.startswith("FLUBNF_")}
    env.update({"HOME": str(home), "FLUBNF_REPO": str(origin),
                "FLUBNF_ENGINE": "public", "FLUBNF_REINSTALL_YES": "1",
                "FLUBNF_REINSTALL_NO_OPEN": "1", "FLUBNF_REINSTALL_NO_INSTALL": "1",
                "FLUBNF_REINSTALL_IGNORE_RUNNING": "1", "GIT_TERMINAL_PROMPT": "0",
                **git})
    out = subprocess.run([BASH, str(REPO / "reinstall.sh")], env=env, text=True,
                         capture_output=True, timeout=180)
    assert out.returncode == 0, out.stdout + out.stderr
    assert "installed from engine-requirements.txt" in out.stdout
    assert not (home / "GitHub/flubnf").exists()
    assert any(p.name.startswith("flubnf-old-") for p in (home / "GitHub").iterdir())
    # the private engine stays, its venv, checkout and file alike
    assert (home / ".venvs/flubnf-engine").is_dir()
    assert (home / "GitHub/PyBNF-Private").is_dir()
    assert archive.exists() and not (home / "Downloads/old-engine-files").exists()
