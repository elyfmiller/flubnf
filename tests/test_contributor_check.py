def _block(lines: list[str], key: str) -> list[str]:
    """The indented lines under a top-level key."""
    i = lines.index(key)
    out = []
    for ln in lines[i + 1:]:
        if not ln.startswith(" "):
            break
        out.append(ln)
    return out


def test_the_workflow_reads_and_runs_nothing_of_the_pull_request():
    lines = [ln for ln in WORKFLOW.read_text(encoding="utf-8").splitlines()
             if ln.strip() and not ln.lstrip().startswith("#")]
    body = "\n".join(lines)
    assert _block(lines, "on:") == ["  pull_request_target:",
                                    "    types: [opened, synchronize, reopened, edited]"]
    assert _block(lines, "permissions:") == ["  contents: read", "  pull-requests: read"]
    assert re.findall(r"uses:\s*(\S+)", body) == ["actions/checkout@v5"]
    assert "with: {persist-credentials: false}" in body
    assert "ref:" not in body
    assert [ln.strip() for ln in lines if "github.event" in ln] == [
        "if: github.event.pull_request.head.repo.full_name != github.repository"]
    runs = [ln.strip() for ln in lines if re.match(r"\s*(- )?run:", ln)]
    assert runs == ["- run: python3 -I .github/contributor_check.py"]
    assert re.search(r"^\s+timeout-minutes: \d+$", body, re.M)
    for word in ("cache", "setup-python", "pip", "secrets", "environment"):
        assert not re.search(rf"\b{word}\b", body), word
    for name in ("GITHUB_ENV", "GITHUB_OUTPUT", "GITHUB_STEP_SUMMARY"):
        assert name not in body and name not in SCRIPT.read_text(encoding="utf-8"), name


