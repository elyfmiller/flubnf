def sha(i: int) -> str:
    return f"{i:040x}"


def commit(i: int, *, author="student", committer="student",
           email="student@example.edu", committer_email=None,
           message="Add the beta2 proposal") -> dict:
    """A pulls/{n}/commits row: a login of "" is a commit linked to no
    account."""
    return {"sha": sha(i),
            "author": {"login": author} if author else None,
            "committer": {"login": committer} if committer else None,
            "commit": {"message": message,
                       "author": {"email": email},
                       "committer": {"email": committer_email or email}}}


def event(**changes) -> dict:
    pr = {"number": 7, "title": "Add the beta2 proposal", "body": "What it changes.",
          "user": {"login": "student"},
          "head": {"sha": HEAD, "repo": {"full_name": "student/flubnf"}},
          "base": {"ref": "dev"}, "commits": 1, "changed_files": 1}
    pr.update(changes)
    return {"pull_request": pr,
            "repository": {"full_name": "owner/flubnf", "default_branch": "main",
                           "owner": {"login": "owner", "id": 123}}}


def nowhere(c: str) -> bool:
    return False


def owner_rules(cc, commits, in_main=nowhere):
    return cc.commit_problems(commits, owner="owner", uid=123, opener="student",
                              in_main=in_main)


def folder(path: str, names=SIX, **entry) -> list[dict]:
    """A tree entry for the folder and one 4 KB plain file per name; entry
    overrides the fields of every file."""
    return [{"path": path, "type": "tree", "mode": "040000"}] + [
        {"path": f"{path}/{n}", "type": "blob", "mode": "100644", "size": 4200, **entry}
        for n in names]


def tree(*entries, truncated=False) -> dict:
    out = [{"path": "proposals", "type": "tree", "mode": "040000"}]
    for e in entries:
        out += e if isinstance(e, list) else [e]
    return {"sha": HEAD, "tree": out, "truncated": truncated}


def blob(path: str, **entry) -> dict:
    return {"path": path, "type": "blob", "mode": "100644", "size": 100, **entry}


def changed(*paths: str) -> list[dict]:
    return [{"filename": p, "status": "added"} for p in paths]


