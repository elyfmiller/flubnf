def test_another_account_is_flagged_not_refused(cc):
    refusals, flags = owner_rules(cc, [commit(1, author="third"),
                                       commit(2, committer="third")])
    assert refusals == []
    tail = "under another GitHub account than this pull request's."
    assert flags == [f"commit `{sha(1)[:8]}` is authored {tail}",
                     f"commit `{sha(2)[:8]}` is committed {tail}"]


def test_mains_merges_are_exempt_and_a_students_commit_is_still_checked(cc):
    # shaped like main's merges: the owner's noreply author, web-flow committing
    merges = [commit(i, author="owner", email=f"123+owner@{NOREPLY}", committer="web-flow",
                     committer_email="web@example.com",
                     message=f"Merge pull request #{60 + i} from owner/dev") for i in (1, 2)]
    # Update branch on the website: the owner's merge on the student's branch
    update = commit(3, author="owner", email=f"123+owner@{NOREPLY}", committer="web-flow",
                    committer_email="web@example.com",
                    message="Merge branch 'dev' into beta2")
    student = commit(4, message="Add beta2\n\nCo-authored-by: X <x@example.org>")
    on_main = {sha(1), sha(2)}
    asked = []
    refusals, flags = owner_rules(cc, merges + [update, student],
                                  in_main=lambda c: asked.append(c) or c in on_main)
    assert refusals == [
        f"commit `{sha(3)[:8]}` is authored {OWNER_WORDS}",
        f"commit `{sha(4)[:8]}` has a co-author or generated-by line (line 3): everything "
        "here is written by people, under their own name. Remove or reword the line and "
        "push again."]
    assert flags == []
    assert asked == [sha(1), sha(2), sha(3)]


