def test_the_template_and_the_guide_pass_their_own_rule(cc):
    # the template's checkbox and the guide's rule both say "co-author or
    # generated-by line" mid-sentence, never at a line's start
    assert cc.credit_lines(TEMPLATE.read_text(encoding="utf-8")) == []
    assert cc.credit_lines(GUIDE.read_text(encoding="utf-8")) == []


def test_no_commit_message_on_head_has_a_credit_line(cc):
    git = shutil.which("git")
    if git is None:
        pytest.skip("git is not on PATH")
    count = subprocess.run([git, "-C", str(REPO), "rev-list", "--count", "HEAD"],
                           capture_output=True, encoding="utf-8")
    if count.returncode or int(count.stdout.strip() or 0) < 1000:
        pytest.skip("a shallow checkout (CI's): the record needs the history")
    log = subprocess.run([git, "-C", str(REPO), "log", "--format=%H%x00%B%x1e", "HEAD"],
                         capture_output=True, encoding="utf-8", errors="replace",
                         check=True).stdout
    hits = []
    for record in log.split("\x1e"):
        full, _, message = record.strip("\n").partition("\x00")
        if cc.credit_lines(message):
            hits.append(full[:8])
    assert hits == []


