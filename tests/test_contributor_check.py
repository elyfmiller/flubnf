class Reader:
    """An injected get: answers by path, an exception answer is raised."""

    def __init__(self, answers: dict):
        self.answers, self.paths = answers, []

    def __call__(self, path: str):
        self.paths.append(path)
        answer = self.answers[path]
        if isinstance(answer, BaseException):
            raise answer
        return answer


def http(code: int) -> urllib.error.HTTPError:
    return urllib.error.HTTPError("https://api.example.com/x", code, "no", None, None)


def page(what: str, k: int = 1) -> str:
    return f"pulls/7/{what}?per_page=100&page={k}"


BASE = "contents/proposals?ref=dev"           # the base branch's proposal folders


def run(cc, tmp_path, capsys, ev, answers, get=True):
    path = tmp_path / "event.json"
    path.write_text(json.dumps(ev), encoding="utf-8", newline="\n")
    reader = Reader(answers)
    code = cc.main({"GITHUB_EVENT_PATH": str(path), "GITHUB_REPOSITORY": "owner/flubnf"},
                   get=reader if get else None)
    return code, capsys.readouterr().out.splitlines(), reader


def test_a_clean_pull_request(cc, tmp_path, capsys):
    code, lines, reader = run(cc, tmp_path, capsys, event(),
                              {page("commits"): [commit(1)],
                               page("files"): changed("docs/SANDBOX.md")})
    assert code == 0
    assert lines == [f"contributor check: pull request #7 at {HEAD}",
                     "contributor check: 0 refused, 0 flagged"]
    assert reader.paths == [page("commits"), page("files")]


def test_a_refusal_exits_1_and_flags_alone_exit_0(cc, tmp_path, capsys):
    code, lines, _ = run(cc, tmp_path, capsys, event(base={"ref": "main"}, changed_files=0),
                         {page("commits"): [commit(1)], page("files"): []})
    assert code == 1
    assert lines[1].startswith("::error::this pull request is against `main`")
    assert lines[-1] == "contributor check: 1 refused, 0 flagged"
    code, lines, _ = run(cc, tmp_path, capsys, event(),
                         {page("commits"): [commit(1, author="third")],
                          page("files"): changed("FluBNF.bat"),
                          f"compare/main...{sha(1)}": {"status": "diverged"}})
    assert code == 0
    assert [ln.split("::")[1] for ln in lines[1:-1]] == ["warning", "warning"]
    assert lines[-1] == "contributor check: 0 refused, 2 flagged"


